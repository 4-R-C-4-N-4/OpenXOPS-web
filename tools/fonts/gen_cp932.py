#!/usr/bin/env python3
"""Generate src/platform/text/cp932_table.inc from Python's 'cp932' codec.

CP932 (Windows-31J) structure:
  single byte : 0x00-0x7F ASCII, 0xA1-0xDF half-width katakana, plus the
                Microsoft extras 0x80 -> U+0080, 0xA0/0xFD-0xFF -> U+F8F0..F8F3
  lead byte   : 0x81-0x9F, 0xE0-0xFC
  trail byte  : 0x40-0x7E, 0x80-0xFC  (note 0x5C '\\' is a valid trail byte)

Output (C++ fragment, included by cp932.cpp):
  static const uint16_t kCp932Single[256];   // 0xFFFF = lead byte, 0xFFFD = invalid
  static const uint16_t kCp932Double[60*189]; // [lead_index][trail-0x40]; 0 = unmapped
All CP932 characters are in the BMP, so uint16_t suffices.

Usage: python3 tools/fonts/gen_cp932.py [out.inc]
"""
import sys
import os

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
assert len(LEADS) == 60
TRAIL_MIN, TRAIL_MAX = 0x40, 0xFC
NTRAIL = TRAIL_MAX - TRAIL_MIN + 1  # 189


def dec(b: bytes):
    try:
        s = b.decode("cp932")
    except UnicodeDecodeError:
        return None
    if len(s) != 1:
        return None
    return ord(s)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(__file__), "..", "..", "src", "platform", "text", "cp932_table.inc")
    single = []
    for b in range(256):
        if b in LEADS:
            single.append(0xFFFF)
        else:
            cp = dec(bytes([b]))
            single.append(0xFFFD if cp is None else cp)
    double = []
    mapped = 0
    for lead in LEADS:
        for t in range(TRAIL_MIN, TRAIL_MAX + 1):
            cp = dec(bytes([lead, t]))
            if cp is None:
                double.append(0)
            else:
                assert 0 < cp <= 0xFFFF
                double.append(cp)
                mapped += 1
    lines = [
        "// GENERATED by tools/fonts/gen_cp932.py from Python's 'cp932' codec. Do not edit.",
        f"// Python {sys.version.split()[0]}; {mapped} double-byte mappings.",
        "// kCp932Single: 0xFFFF = lead byte, 0xFFFD = invalid single byte.",
        "// kCp932Double[(lead index)*189 + (trail-0x40)]: 0 = unmapped.",
        "static const uint16_t kCp932Single[256] = {",
    ]
    for i in range(0, 256, 16):
        lines.append("  " + ",".join(f"0x{v:04X}" for v in single[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const uint16_t kCp932Double[{len(double)}] = {{")
    for i in range(0, len(double), 16):
        lines.append("  " + ",".join(f"0x{v:04X}" for v in double[i:i + 16]) + ",")
    lines.append("};")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}: {mapped} double-byte mappings, {os.path.getsize(out)} bytes")


if __name__ == "__main__":
    main()
